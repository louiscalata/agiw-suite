/** Choice components: presentation only. No fetching, timers, model calls or inferred edges. */
export function choiceState(word) {
  const value = String(word || 'UNKNOWN').toUpperCase();
  const glyph = {OK:'●', READY:'●', RUNNING:'▶', BLOCKED:'✕', UNKNOWN:'?', REVIEW:'◆'}[value] || '○';
  return {word:value, glyph};
}
export function declaredNeighbours(steps, id) {
  const step = steps.find(item => item.id === id);
  if (!step) return {inputs:[], outputs:[], declared:false};
  const inputs = Array.isArray(step.inputs) ? steps.filter(item => step.inputs.includes(item.id)) : [];
  const outputs = steps.filter(item => Array.isArray(item.inputs) && item.inputs.includes(id));
  return {inputs, outputs, declared:Array.isArray(step.inputs)};
}
export function hiddenGroup(steps, kind = 'optional') {
  const attention = steps.filter(item => ['BLOCKED','UNKNOWN','REVIEW','STALE'].includes(String(item.word || item.status || 'UNKNOWN').toUpperCase()));
  return {locked:attention.length > 0, label:attention.length
    ? `opened: ${attention.length} inside need attention — cannot hide`
    : `[+${steps.length} ${kind}] steps — ${kind === 'optional' ? 'off by default' : 'will run'}`};
}
export function eventTick(previous, event) {
  if (!event || typeof event.runId !== 'string' || !event.runId || typeof event.id !== 'string' || !event.id) return previous;
  const state = previous?.runId === event.runId ? previous : {runId:event.runId, ids:[], count:0};
  if (state.ids.includes(event.id)) return state;
  const count = state.count + 1;
  return {runId:event.runId, ids:[...state.ids,event.id], count, glyphs:'▰'.repeat(Math.min(8,count)), label:`${count} this run`};
}
function choiceElement(doc, tag, className, text) {
  const node = doc.createElement(tag);
  if (className) node.className = className;
  if (text !== undefined) node.textContent = text;
  return node;
}
function choiceButton(doc, text, action) {
  const button = choiceElement(doc, 'button', 'jp-button', text);
  button.type = 'button';
  button.addEventListener('click', action);
  return button;
}
function stepName(step) { return `${step.name || step.label || step.id} · step_id: ${step.id}`; }

/** Native dialog supplies modal inertness, Escape and focus containment. */
export function mountCommandPalette(doc, opener, commands) {
  const dialog = choiceElement(doc, 'dialog', 'jp-palette');
  dialog.setAttribute('aria-label', 'Commands');
  const label = choiceElement(doc, 'label', '', 'Find a command');
  const input = choiceElement(doc, 'input', 'jp-command-input');
  const id = `jp-command-${mountCommandPalette.sequence = (mountCommandPalette.sequence || 0) + 1}`;
  input.setAttribute('role','combobox'); input.setAttribute('aria-autocomplete','list');
  input.setAttribute('aria-expanded','false'); input.setAttribute('aria-controls',id);
  label.append(input);
  const list = choiceElement(doc,'div','jp-command-results'); list.id=id; list.setAttribute('role','listbox');
  const live = choiceElement(doc,'p','jp-live'); live.setAttribute('role','status');
  const close = choiceButton(doc,'Close',() => dialog.close());
  dialog.append(label,list,live,close); doc.body.append(dialog);
  let options=[], current=0;
  const activate = () => {
    options.forEach((node,i) => node.setAttribute('aria-selected',String(i===current)));
    if (options[current]) input.setAttribute('aria-activedescendant',options[current].id);
    else input.removeAttribute('aria-activedescendant');
  };
  const paint = () => {
    list.replaceChildren(); current=0;
    const source = typeof commands === 'function' ? commands() : commands;
    const matches = source.filter(item => item.label.toLowerCase().includes(input.value.toLowerCase()));
    options = matches.map((item,i) => {
      const node = choiceElement(doc,'div','jp-command-option',item.label + (item.reason ? ` (n/a: ${item.reason})` : ''));
      node.id=`${id}-${i}`; node.setAttribute('role','option'); node.setAttribute('aria-disabled',String(Boolean(item.reason)));
      node.run = () => { if (item.reason) { live.textContent=item.reason; return; } dialog.close(); item.run?.(); };
      node.addEventListener('click',node.run); list.append(node); return node;
    });
    live.textContent=`${matches.length} command${matches.length===1?'':'s'}`; activate();
  };
  const open = (query = '') => { if (dialog.open) return; input.value=query; paint(); dialog.showModal(); input.setAttribute('aria-expanded','true'); input.focus(); };
  opener.addEventListener('click',() => open());
  input.addEventListener('input',paint);
  input.addEventListener('keydown',event => {
    if (['ArrowDown','ArrowUp','Home','End'].includes(event.key)) {
      event.preventDefault();
      if (options.length) current=event.key==='Home'?0:event.key==='End'?options.length-1:(current+(event.key==='ArrowDown'?1:-1)+options.length)%options.length;
      activate(); options[current]?.scrollIntoView?.({block:'nearest'});
    }
    if (event.key==='Enter') { event.preventDefault(); options[current]?.run(); }
  });
  dialog.addEventListener('close',() => { input.setAttribute('aria-expanded','false'); if (opener.isConnected && (!doc.activeElement || doc.activeElement === doc.body || dialog.contains(doc.activeElement))) opener.focus(); });
  return {open, dialog, query:() => input.value, destroy:() => dialog.remove()};
}

export function mountChoicePipeline(host, config) {
  const doc=host.ownerDocument, steps=Array.isArray(config.steps)?config.steps:[];
  const previous=host.choiceCleanup; previous?.(); host.replaceChildren();
  host.classList.add('jp-workbench');
  const spine=choiceElement(doc,'div','jp-spine'); spine.setAttribute('role','toolbar'); spine.setAttribute('aria-label','Pipeline stations');
  const inspector=choiceElement(doc,'dialog','jp-inspector'); inspector.setAttribute('aria-label','Step inspector');
  const title=choiceElement(doc,'h3','jp-inspector-title','No step selected'); title.tabIndex=-1;
  title.dataset.focusKey='inspector-title';
  const detail=choiceElement(doc,'div','jp-inspector-content');
  const controls=choiceElement(doc,'div','jp-pager');
  const close=choiceButton(doc,'Close',() => inspector.close()); close.classList.add('jp-sheet-close');
  close.dataset.focusKey='inspector-close';
  inspector.append(close,title,detail,controls); host.append(spine,inspector);
  // Reserve the side column only when the station rows and inspector both fit.
  const media=doc.defaultView.matchMedia('(max-width: 1199px)');
  let selected=steps.find(item => item.id===config.selectedId) || null;
  let opener=null, focusAfter=null;
  const buttons=new Map();
  const groups=new Map();
  const palettes=[];
  const forks=new Set();
  const live=choiceElement(doc,'p','jp-live'); live.setAttribute('role','status'); host.append(live);
  const relation = () => declaredNeighbours(steps,selected?.id);
  const restore = () => { if (opener?.isConnected) opener.focus(); };
  inspector.addEventListener('close',() => { if (media.matches) { host.append(controls); restore(); } });
  const layout = () => {
    if (media.matches) { if (inspector.open && !inspector.matches(':modal')) inspector.close(); if (!inspector.open) host.append(controls); }
    else { if (inspector.open) inspector.close(); inspector.append(controls); inspector.show(); }
  };
  const reveal = step => {
    if (step.group && groups.has(step.group)) {
      const group=groups.get(step.group); group.body.hidden=false; group.toggle.setAttribute('aria-expanded','true');
    }
  };
  const select = (step, focus=false) => {
    reveal(step); selected=step; paint(); config.onSelect?.(step.id);
    if (media.matches) { opener=buttons.get(step.id); inspector.append(controls); if (!inspector.open) inspector.showModal(); title.focus(); }
    else if (focus) buttons.get(step.id)?.focus();
  };
  const destinations = (items, direction) => {
    if (items.length===1) {
      const button = choiceButton(doc,`${direction} ${items[0].name || items[0].label || items[0].id}`,() => {
      focusAfter=direction; select(items[0]);
      controls.querySelector(`[data-direction="${direction}"]`)?.focus();
      });
      button.setAttribute('aria-label', `${direction} ${stepName(items[0])}`);
      return button;
    }
    const button=choiceButton(doc,items.length?`${direction} choose (${items.length})`:`${direction} — unavailable`,() => {
      if (!items.length) return;
      const chooser=choiceElement(doc,'dialog','jp-branches'); chooser.setAttribute('aria-label',`Fork: ${items.length} ${direction.toLowerCase()} steps — choose one`);
      chooser.append(choiceElement(doc,'p','',`Fork: ${items.length} steps — choose one`));
      for (const step of items) chooser.append(choiceButton(doc,stepName(step),() => { chooser.close(); select(step,true); }));
      chooser.append(choiceButton(doc,'Close',() => chooser.close())); doc.body.append(chooser); forks.add(chooser);
      chooser.addEventListener('close',() => { chooser.remove(); forks.delete(chooser); if(button.isConnected) button.focus(); }); chooser.showModal();
    });
    button.disabled=!items.length; return button;
  };
  function paint() {
    const nearby=relation();
    for (const step of steps) {
      const button=buttons.get(step.id), on=step===selected;
      const kind=nearby.inputs.includes(step)?'← input':nearby.outputs.includes(step)?'output →':'';
      button.setAttribute('aria-pressed',String(on)); button.tabIndex=on || (!selected && step===steps[0])?0:-1;
      button.dataset.neighbour=kind; button.querySelector('.jp-relation').textContent=on?'▶ Selected':kind;
      button.setAttribute('aria-label',`${stepName(step)}, ${choiceState(step.word).word}${on?', selected':kind?`, ${kind}`:''}`);
    }
    title.textContent=selected ? selected.name || selected.label || selected.id : 'No step selected';
    detail.replaceChildren(); controls.replaceChildren();
    if (!selected) detail.append(choiceElement(doc,'p','','No step selected. Select a step on the spine to inspect it.'));
    else {
      detail.append(choiceElement(doc,'p','jp-subline',`step_id: ${selected.id}`));
      detail.append(choiceElement(doc,'p','',selected.reason || selected.detail || 'No detail declared. Inspect the source record for this step.'));
      detail.append(choiceElement(doc,'p','',nearby.declared?'Declared neighbours':'Dependencies not declared; pager and bindings are unavailable.'));
      for (const [word,items] of [['IN ←',nearby.inputs],['OUT →',nearby.outputs]]) for (const step of items) {
        const button=choiceButton(doc,`${word} ${stepName(step)}`,() => select(step,true));
        button.dataset.focusKey=`neighbour:${word}:${step.id}`; detail.append(button);
      }
      const bindings=choiceElement(doc,'ul','jp-bindings');
      for (const binding of selected.bindings || []) {
        const row=choiceElement(doc,'li','',`${binding.name} ← ${binding.source}`);
        const edit=choiceButton(doc,'Change',() => config.onBind?.(selected.id,binding));
        edit.dataset.focusKey=`binding:${selected.id}:${binding.name}`;
        edit.disabled=typeof config.onBind!=='function'; row.append(edit); bindings.append(row);
      }
      if (!bindings.children.length) bindings.append(choiceElement(doc,'li','','No editable bindings declared. Consult the adaptor to configure inputs.'));
      detail.append(bindings);
      if (config.openMonitor) {
        const jump=choiceButton(doc,'Open monitor',() => {});
        jump.dataset.openMonitor=selected.id; detail.append(jump);
        jump.dataset.focusKey=`monitor:${selected.id}`;
      }
    }
    for (const [word,items] of [['Prev',nearby.inputs],['Next',nearby.outputs]]) {
      const button=destinations(items,word); button.dataset.direction=word;
      button.dataset.focusKey=`direction:${word}`;
      button.title=items.length===1?stepName(items[0]):items.length?`Fork: ${items.length} steps — choose one`:'No dependency declared'; controls.append(button);
    }
    const inspect=choiceButton(doc,'Inspect',() => { if(selected) select(selected,true); }); inspect.disabled=!selected; inspect.classList.add('jp-primary'); controls.insertBefore(inspect,controls.lastChild);
    inspect.dataset.focusKey='inspect';
    const more=choiceButton(doc,'⌘ More',() => {}); controls.append(more);
    more.dataset.focusKey='more';
    for (const palette of palettes.splice(0)) palette.destroy();
    palettes.push(mountCommandPalette(doc,more,steps.map(step => ({label:stepName(step),run:() => select(step,true)}))));
    live.textContent=selected ? `Selected ${stepName(selected)}` : 'No step selected';
    if (focusAfter) { controls.querySelector(`[data-direction="${focusAfter}"]`)?.focus(); focusAfter=null; }
  }
  for (const step of steps) {
    const state=choiceState(step.word);
    const button=choiceElement(doc,'button','jp-step jk-station'); button.type='button'; button.dataset.station=step.id; button.dataset.state=state.word;
    button.dataset.focusKey=`station:${step.id}`;
    const port=choiceElement(doc,'span','jp-port','IN ←');
    const name=choiceElement(doc,'span','jp-name jk-station-name',step.name || step.label || step.id);
    const sub=choiceElement(doc,'span','jp-subline',`step_id: ${step.id}`);
    const status=choiceElement(doc,'span','jp-state',`${state.glyph} [${state.word}]`);
    button.append(port,name,sub,status,choiceElement(doc,'span','jp-relation'),choiceElement(doc,'span','jp-port','OUT →'));
    if (state.word==='UNKNOWN') button.append(choiceElement(doc,'span','jp-unknown-reason',step.reason || 'Not declared by adaptor'));
    button.addEventListener('click',() => select(step)); buttons.set(step.id,button);
    if (step.group) {
      if (!groups.has(step.group)) {
        const members=steps.filter(item => item.group===step.group), policy=hiddenGroup(members,step.optional?'optional':'collapsed');
        const body=choiceElement(doc,'div','jp-group'); body.hidden=!policy.locked;
        const toggle=choiceButton(doc,policy.label,() => { body.hidden=!body.hidden; toggle.setAttribute('aria-expanded',String(!body.hidden)); });
        toggle.dataset.focusKey=`group:${step.group}`;
        toggle.classList.add('jp-gap'); toggle.setAttribute('aria-expanded',String(!body.hidden)); toggle.disabled=policy.locked;
        spine.append(toggle,body); groups.set(step.group,{body,toggle});
      }
      groups.get(step.group).body.append(button);
    } else spine.append(button);
  }
  if (!steps.length) spine.append(choiceElement(doc,'p','jp-empty','No steps declared in this sample. Check the source connection.'));
  spine.addEventListener('keydown',event => {
    if (!['ArrowDown','ArrowRight','ArrowUp','ArrowLeft','Home','End'].includes(event.key)) return;
    const current=steps.findIndex(step => buttons.get(step.id)===doc.activeElement); if(current<0) return;
    event.preventDefault(); const delta=['ArrowDown','ArrowRight'].includes(event.key)?1:-1;
    const next=event.key==='Home'?0:event.key==='End'?steps.length-1:(current+delta+steps.length)%steps.length; select(steps[next],true);
  });
  if (selected) reveal(selected);
  paint(); layout(); media.addEventListener?.('change',layout);
  if (config.resume?.sheetOpen && media.matches && selected) {
    opener=buttons.get(selected.id); inspector.append(controls); inspector.showModal();
  }
  const shortcut = event => {
    if ((event.metaKey || event.ctrlKey) && event.key.toLowerCase()==='k' && !doc.querySelector('.jp-palette[open]')) {
      event.preventDefault(); event.stopPropagation(); palettes[0]?.open();
    }
  };
  host.addEventListener('keydown',shortcut);
  const region=choiceElement(doc,'div','jp-ledger-region'); region.tabIndex=0; region.setAttribute('role','region'); region.setAttribute('aria-label','Declared step ledger');
  region.dataset.focusKey='ledger';
  const table=choiceElement(doc,'table','jp-ledger');
  table.append(choiceElement(doc,'caption','','Declared step ledger'));
  const heading=choiceElement(doc,'tr');
  for (const name of ['Step','State','Duration (ms)']) { const cell=choiceElement(doc,'th','',name); cell.setAttribute('scope','col'); heading.append(cell); }
  const head=choiceElement(doc,'thead'); head.append(heading); table.append(head);
  const body=choiceElement(doc,'tbody');
  for (const step of steps) {
    const state=choiceState(step.word), row=choiceElement(doc,'tr'); row.dataset.state=state.word;
    const name=choiceElement(doc,'th','',step.name || step.label || step.id); name.setAttribute('scope','row');
    row.append(name,choiceElement(doc,'td','',`${state.glyph} [${state.word}]`),choiceElement(doc,'td','',typeof step.durationMs==='number' && Number.isFinite(step.durationMs) && step.durationMs>=0 ? String(step.durationMs) : 'Unknown'));
    body.append(row);
  }
  table.append(body); region.append(table); host.append(region);
  if (config.resume?.paletteOpen) palettes[0]?.open(config.resume.query);
  else if (config.resume?.focused) {
    const target=config.resume.focusKey
      ? [...host.querySelectorAll('[data-focus-key]')].find(node => node.dataset.focusKey===config.resume.focusKey)
      : config.resume.direction ? controls.querySelector(`[data-direction="${config.resume.direction}"]`)
      : media.matches && inspector.open ? title : buttons.get(selected?.id);
    const step=steps.find(item => item.id===target?.dataset.station);
    if (step) reveal(step);
    target?.focus();
  }
  let tick=null;
  const receiveEvent = event => {
    if (config.eventStreamDeclared!==true) return;
    tick=eventTick(tick,event);
    if (tick) live.textContent=`Event received: ${tick.glyphs} ${tick.label}`;
  };
  host.choiceViewState=() => ({
    sheetOpen:inspector.matches(':modal'),
    focused:host.contains(doc.activeElement),
    focusKey:host.contains(doc.activeElement) ? doc.activeElement?.dataset?.focusKey : undefined,
    direction:doc.activeElement?.dataset?.direction,
    paletteOpen:palettes[0]?.dialog.open===true,
    query:palettes[0]?.query() || '',
  });
  host.choiceCleanup=() => {
    host.removeEventListener('keydown',shortcut);
    media.removeEventListener?.('change',layout);
    for(const palette of palettes) palette.destroy();
    for(const chooser of forks) { chooser.close(); chooser.remove(); }
    forks.clear();
  };
  return {select, receiveEvent, cleanup:host.choiceCleanup};
}
