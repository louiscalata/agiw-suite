/** Deterministic UI exports. No server, browser, model or network dependency. */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
export const TOKEN_START = '/* BEGIN JARYO CHOICE TOKENS — generated by jaryo/generate.mjs */';
export const TOKEN_END = '/* END JARYO CHOICE TOKENS */';
export const PATTERN_START = '/* BEGIN JARYO CHOICE COMPONENTS — generated by jaryo/generate.mjs */';
export const PATTERN_END = '/* END JARYO CHOICE COMPONENTS */';
export const JS_START = '/* BEGIN JARYO CHOICE BEHAVIOR — generated by jaryo/generate.mjs */';
export const JS_END = '/* END JARYO CHOICE BEHAVIOR */';

const colorNames = {
  bg: 'bg', surface: 'surface', text: 'text', muted: 'muted', border: 'border',
  focus_ring: 'focus', selected_bg: 'invert', selected_fg: 'invert-ink',
  accent_identity: 'accent', accent_ink: 'accent-ink', status_ok: 'status-ok',
  status_run: 'status-run', status_blocked: 'status-blocked', status_blocked_bg: 'blocked-bg',
  status_unknown: 'status-unknown', sel_sub: 'sel-sub', sel_blocked: 'sel-blocked', sel_run: 'sel-run',
};
function colors(palette) {
  return Object.entries(colorNames).map(([key, name]) => `  --j-${name}: ${palette[key]};`).join('\n');
}
export function choiceTokens(tokens) {
  const light = colors(tokens.palette.light);
  const dark = colors(tokens.palette.dark);
  return `${TOKEN_START}
:root {
  color-scheme: dark;
${dark}
  --j-grid: transparent;
  --j-font: "IBM Plex Sans", "Liberation Sans", "Noto Sans", sans-serif;
  --j-mono: "IBM Plex Mono", ui-monospace, "Cascadia Mono", Menlo, Consolas, monospace;
  --j-motion: ${tokens.interaction.motion};
  --j-thumb-bar: ${tokens.interaction.thumbBar};
  --j-inspector-min: ${tokens.interaction.inspectorMin};
  --j-inspector-max: ${tokens.interaction.inspectorMax};
  --j-unknown-hatch: ${tokens.interaction.unknownHatch};
}
@media (prefers-color-scheme: light) {
  html:not([data-theme="dark"]) {
    color-scheme: light;
${light}
  }
}
html[data-theme="dark"] {
  color-scheme: dark;
${dark}
}
html[data-theme="light"] {
  color-scheme: light;
${light}
}
@media (forced-colors: active) {
  :root, html[data-theme], html:not([data-theme="dark"]) {
    --j-bg: Canvas; --j-surface: Canvas; --j-text: CanvasText;
    --j-muted: CanvasText; --j-border: CanvasText; --j-focus: Highlight;
    --j-invert: Highlight; --j-invert-ink: HighlightText;
    --j-accent: Highlight; --j-accent-ink: HighlightText;
    --j-status-ok: CanvasText; --j-status-run: CanvasText;
    --j-status-blocked: CanvasText; --j-blocked-bg: Canvas;
    --j-status-unknown: CanvasText;
    --j-sel-sub: HighlightText; --j-sel-blocked: HighlightText; --j-sel-run: HighlightText;
  }
}
${TOKEN_END}`;
}
export function primitives(tokens) {
  const s = tokens.scale;
  const vars = {};
  for (const group of ['space', 'type', 'leading', 'tracking']) {
    for (const [name, value] of Object.entries(s[group])) vars[`--j-${group}-${name}`] = value;
  }
  for (const [key, name] of Object.entries({borderWidth:'border-width',focusWidth:'focus-width',focusOffset:'focus-offset',radius:'radius',controlMin:'control-min',sidebar:'sidebar',grid:'grid-size'})) vars[`--j-${name}`] = s[key];
  for (const [key, value] of Object.entries(s.breakpoints)) vars[`--j-bp-${key}`] = value;
  vars['--j-font-display'] = 'var(--j-font)';
  return `${choiceTokens(tokens)}\n/* The original dimensional scale is retained for Android compatibility. */\n:root {\n${Object.entries(vars).map(([key,value]) => `  ${key}: ${value};`).join('\n')}\n}\n@media (prefers-reduced-motion: reduce) {\n  .j-schematic { animation: none; transition: none; }\n}\n`;
}
export function replaceBlock(source, start, end, block) {
  const a = source.indexOf(start);
  if (a < 0) return `${source.trimEnd()}\n\n${block}\n`;
  const b = source.indexOf(end, a);
  if (b < 0) throw new Error(`Unclosed generated block: ${start}`);
  return source.slice(0, a) + block + source.slice(b + end.length);
}
export function outputs(root = here) {
  const tokens = JSON.parse(readFileSync(join(root, 'tokens.json'), 'utf8'));
  const patterns = readFileSync(join(root, 'patterns.css'), 'utf8');
  const behavior = readFileSync(join(root, 'interactions.mjs'), 'utf8');
  const out = new Map([['primitives.css', primitives(tokens)]]);
  const web = join(root, '../web/jaryo.css');
  if (existsSync(web)) {
    let css = readFileSync(web, 'utf8');
    css = replaceBlock(css, TOKEN_START, TOKEN_END, choiceTokens(tokens));
    css = replaceBlock(css, PATTERN_START, PATTERN_END, `${PATTERN_START}\n${patterns.trimEnd()}\n${PATTERN_END}`);
    out.set('../web/jaryo.css', css);
    const js = readFileSync(join(root, '../web/jaryo.mjs'), 'utf8');
    out.set('../web/jaryo.mjs', replaceBlock(js, JS_START, JS_END, `${JS_START}\n${behavior.trimEnd()}\n${JS_END}`));
  }
  return out;
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const check = process.argv.includes('--check');
  let drift = 0;
  for (const [file, expected] of outputs()) {
    const path = join(here, file);
    if (check) {
      if (readFileSync(path, 'utf8') !== expected) { console.error(`DRIFT ${file}`); drift++; }
    } else writeFileSync(path, expected);
  }
  console.log(check ? `Jaryo exports: ${drift} drift(s)` : 'Generated Jaryo UI exports');
  process.exitCode = drift ? 1 : 0;
}
