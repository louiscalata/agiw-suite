"""Generated relational dimensions missing from the original degradation matrix.

Every case traverses server.once, projection and JSON. Endpoint cardinality cases
also run the real collector and PAIR parser with injected HTTP responses. Oracles
describe the supplied evidence, without calling production validation helpers.
"""
