def emit(value, dimension, coordinates, expect, *, cached=False):
    class Collector:
        def collect(self):
            return copy.deepcopy(value)
    payload = server.once(Collector(), clock=lambda: NOW, sleep=lambda _: None,
                          state_dir=fixture_path('no-cache'))
    if cached:
        class NoProbe:
            def collect(self):
                raise AssertionError('valid cached peer must not be replaced by a probe')
        with tempfile.TemporaryDirectory() as temporary:
            state = Path(temporary).resolve() / 'state'
            server.write_status(state, json.loads(payload))
            payload = server.once(NoProbe(), clock=lambda: NOW, state_dir=state)
    return {'family': 'shape', 'activity': 'mixed', 'mutations': [], 'dimension': dimension,
            'coordinates': coordinates, 'expect': expect, 'now': NOW, 'snapshot': json.loads(payload)}


def check(group, path, value):
    return {'group': group, 'path': path.split('.'), 'value': value}


def aggregate(known, count=None, group='F1'):
    return [check(group, 'modelsComplete', known), check(group, 'modelsTotal', count if known else None),
            {'group': group, 'aggregate': known, 'count': count}]


def pair_rows(count, style, states):
    def name(index):
        if style == 'tagged':
            return f'model-{index}:q4'
        if style == 'paths':
            return f'/private/models/model-{index}.gguf'
        if style == 'duplicate':
            return 'same'
        if style == 'alias-collision':
            return f'/private/{index}/same.gguf'
        if style == 'long-collision':
            return 'x' * 120 + str(index)
        return f'model-{index}'
    return [{'id': name(i), 'status': {'value': states[i % len(states)]}} for i in range(count)]


def public_name(name):
    # Independent fixture expectation, not lanes.public_id.
    return name.rsplit('/', 1)[-1][:120]


def shape_cases():
    with patch.object(probes, '_http_get', new=forbidden), \
            patch.object(probes, 'read_codex_state', new=lambda *a, **k: {}), \
            patch.object(probes, 'read_pair_files', new=lambda *a, **k: {}), \
            patch.object(probes, 'last_rates', new=lambda *a, **k: {}):
        fixture = FixtureCollector([], 'idle')
        fixture.collect()
        base = fixture.collect()

        # Missing KEY is different from null; subset rows are different from malformed rows.
        # Two wrappers exercise omission of a single contributor, not only a whole family.
        for model_count, lane_mode, reverse in itertools.product(
                (0, 1, 3), ('complete', 'missing-key', 'null', 'empty', 'pair-only',
                            'wrappers-only', 'omit-second-wrapper', 'unrelated-only'), (False, True)):
            value = copy.deepcopy(base)
            wrapper = next(row for row in value['lanes'] if row['id'] == 'gpu-wrapper-101')
            value['lanes'].append({**wrapper, 'id': 'gpu-wrapper-202'})
            value['models'] = [{'id': f'witness-{i}', 'loadedState': 'inactive', 'activity': 'unknown',
                                'lane': ('pair-llamacpp', 'gpu-wrapper-101', 'gpu-wrapper-202')[i]}
                               for i in range(model_count)]
            # A bounded explicit witness is generated by the collector before projection.
            value['modelInventoryLanes'] = ['pair-llamacpp', 'gpu-wrapper-101', 'gpu-wrapper-202']
            if lane_mode == 'missing-key':
                value.pop('lanes')
            elif lane_mode == 'null':
                value['lanes'] = None
            elif lane_mode == 'empty':
                value['lanes'] = []
            elif lane_mode == 'pair-only':
                value['lanes'] = [row for row in value['lanes'] if row['id'] == 'pair-llamacpp']
            elif lane_mode == 'wrappers-only':
                value['lanes'] = [row for row in value['lanes'] if row['id'].startswith('gpu-wrapper-')]
            elif lane_mode == 'omit-second-wrapper':
                value['lanes'] = [row for row in value['lanes'] if row['id'] != 'gpu-wrapper-202']
            elif lane_mode == 'unrelated-only':
                value['lanes'] = [row for row in value['lanes'] if row['id'] == 'coordinator']
            if reverse and isinstance(value.get('lanes'), list):
                value['lanes'].reverse()
            yield emit(value, 'inventory-witness', [model_count, lane_mode, reverse],
                       aggregate(lane_mode == 'complete', model_count))
            yield emit(value, 'cached-inventory-witness', [model_count, lane_mode, reverse],
                       aggregate(lane_mode == 'complete', model_count), cached=True)

        for witness in (None, [], ['pair-llamacpp'], ['gpu-wrapper-101'],
                        ['pair-llamacpp', 'gpu-wrapper-101', 'gpu-wrapper-101'],
                        ['pair-llamacpp', 'gpu-wrapper-101', None]):
            value = copy.deepcopy(base)
            value['modelInventoryLanes'] = witness
            yield emit(value, 'inventory-witness-shape', [witness], aggregate(False))

        # Cardinality, identity spelling/collisions, state mix, and ordering are independent axes.
        for count, style, states, reverse in itertools.product(
                (1, 2, 3, 31, 32, 33),
                ('plain', 'tagged', 'paths', 'duplicate', 'alias-collision', 'long-collision'),
                (('loaded', 'unloaded'), ('unloaded', 'loaded'), ('loaded', 'loading')), (False, True)):
            supplied = pair_rows(count, style, states)
            if reverse:
                supplied.reverse()
            class PairCollector(FixtureCollector):
                def fetch(self, url, *args):
                    if url.endswith(':8081/models'):
                        return {'data': copy.deepcopy(supplied)}
                    return super().fetch(url, *args)
            collector = PairCollector([], 'idle')
            collector.collect()
            value = collector.collect()
            endpoint_valid = count <= 32 and not (style == 'duplicate' and count > 1)
            collision = count > 1 and style in ('alias-collision', 'long-collision')
            expected = []
            if endpoint_valid:
                expected = [{'id': public_name(row['id']), 'lane': 'pair-llamacpp',
                             'state': 'unknown' if collision or row['status']['value'] == 'loading'
                             else 'loaded' if row['status']['value'] == 'loaded' else 'inactive'}
                            for row in supplied]
                expected.append({'id': 'fixture-gpu', 'lane': 'gpu-wrapper-101', 'state': 'loaded'})
                expected.sort(key=lambda row: row['state'] != 'loaded')
                expected = expected[:32]
            group = 'N1' if collision else 'F2'
            expectations = [{'group': group, 'modelDetails': expected, 'ambiguous': collision}]
            if not endpoint_valid:
                expectations = [check('F2', 'modelsComplete', False),
                                {'group': 'F2', 'modelDetails': [{'id': 'fixture-gpu', 'lane': 'gpu-wrapper-101', 'state': 'loaded'}]}]
            elif not collision:
                expectations += aggregate(count + 1 <= 32, count + 1, group='F2')
            else:
                expectations += aggregate(False, group='N1')
            yield emit(value, 'model-cardinality-identity', [count, style, states, reverse], expectations)

        # A duplicate in the truncated tail still invalidates the retained identity.
        for count, collision, reverse in itertools.product((31, 32, 33, 64), (False, True), (False, True)):
            value = copy.deepcopy(base)
            value['models'] = [{'id': f'/private/a/model-{i}', 'lane': 'pair-llamacpp',
                                'loadedState': 'loaded', 'activity': 'unknown'} for i in range(count)]
            if collision:
                value['models'][-1]['id'] = '/private/b/model-0'
            if reverse:
                value['models'].reverse()
            expectations = aggregate(count <= 32 and not collision, count, group='N1')
            expectations.append({'group': 'N1', 'ambiguousId': 'model-0' if collision else None})
            yield emit(value, 'bounded-model-tail', [count, collision, reverse], expectations)

        # Lane-wide activity cannot be copied onto several model identities.
        for count, activity, inactive in itertools.product((1, 2, 3, 32), ('idle', 'generating'), (False, True)):
            value = copy.deepcopy(base)
            busy = int(activity == 'generating')
            lane = next(row for row in value['lanes'] if row['id'] == 'gpu-wrapper-101')
            lane.update(status='busy' if busy else 'idle', phase=activity, slotsBusy=busy,
                        slotsTotal=1, liveTokensPerSecond=10 if busy else None)
            value['models'] = [{'id': f'shared-{i}', 'lane': lane['id'],
                                'loadedState': 'inactive' if inactive and i == count - 1 else 'loaded',
                                'activity': activity, 'slotsBusy': busy, 'slotsTotal': 1,
                                'liveTokensPerSecond': 10 if busy else None} for i in range(count)]
            expected = activity if count == 1 and not inactive else 'unknown'
            yield emit(value, 'shared-lane-activity', [count, activity, inactive],
                       [{'group': 'N3', 'modelActivity': expected}])

        # Producer consistency is checked before the UI can hide contradictory lane counters.
        for lane_id, health, status, reason in itertools.product(
                ('gpu-wrapper-101', 'pair-llamacpp', 'coordinator'),
                (None, 'unknown', 'down', 'up'), ('idle', 'busy', 'serving', 'active', 'absent', 'disabled'),
                ('timeout', 'observed')):
            value = copy.deepcopy(base)
            value['lanes'] = [{'id': lane_id, 'health': health, 'status': status, 'reason': reason,
                               'phase': 'generating' if status == 'busy' else 'idle',
                               'slotsBusy': 1 if status == 'busy' else 0, 'slotsTotal': 1,
                               'liveTokensPerSecond': 10}]
            up = health == 'up' and status in ('idle', 'busy', 'serving', 'active')
            down = health == 'down' and lane_id == 'coordinator' and status in ('absent', 'disabled')
            expected_status = status if up or down else 'unknown'
            expected_activity = ('generating' if status == 'busy' else 'idle') if up and status in ('idle', 'busy') else 'unknown'
            expectations = [check('F3', 'lanes.0.status', expected_status),
                            check('F3', 'lanes.0.activity', expected_activity)]
            if expected_activity == 'unknown':
                expectations += [check('F3', 'lanes.0.' + key, None)
                                 for key in ('slotsBusy', 'slotsTotal', 'liveTokensPerSecond')]
            yield emit(value, 'lane-health-activity', [lane_id, health, status, reason], expectations)

        # A valid listener feed does not certify caller visibility; boundaries include empty and capped tails.
        callers = [None, [], [{'name': 'Claude Code', 'lane': 'gpu-wrapper', 'connections': 1}],
                   [{'name': 'unknown', 'lane': 'gpu-wrapper', 'connections': 1}],
                   [{'name': 'codex', 'lane': 'gpu-wrapper', 'connections': 1}] * 32,
                   [{'name': 'codex', 'lane': 'gpu-wrapper', 'connections': 1}] * 33,
                   [{'name': 'codex', 'lane': 'gpu-wrapper', 'connections': 1}, None]]
        for caller_index, caller_state, listener_mode in itertools.product(range(len(callers)), ('known', 'unknown', None), ('valid', 'invalid')):
            value = copy.deepcopy(base)
            value['network'].update(callers=copy.deepcopy(callers[caller_index]), callersState=caller_state)
            if listener_mode == 'invalid':
                value['network']['listeners'].append(None)
            known = caller_state == 'known' and caller_index in (1, 2, 4) and listener_mode == 'valid'
            yield emit(value, 'independent-caller-visibility', [caller_index, caller_state, listener_mode],
                       [check('F4', 'network.callersState', 'known' if known else 'unknown'),
                        {'group': 'F4', 'callersKnown': known}])

        # Cross evidence-window boundaries with a second healthy peer and incomplete caller visibility.
        # This validates mixed-feed isolation and the reason used when current evidence expires.
        for age, skew, feed_fresh, incomplete in itertools.product(
                (-.001, 0, 9.999, 10, 10.001), (0, -.009, .009, -.011, .011), (False, True), (False, True)):
            value = copy.deepcopy(base)
            if incomplete:
                value['network'].update(callers=None, callersState='unknown')
            entry = emit(value, 'clock-window-mixed-feeds', [age, skew, feed_fresh, incomplete], [])
            entry['snapshot']['observedUnix'] = NOW - age
            import datetime as dt
            entry['snapshot']['observedAt'] = dt.datetime.fromtimestamp(NOW - age + skew, dt.timezone.utc).isoformat()
            entry['viewOptions'] = {'feedFresh': feed_fresh}
            fresh = feed_fresh and 0 <= age <= 10 and abs(skew) <= .01
            entry['expect'] = [{'group': 'N2', 'fresh': fresh}, {'group': 'F4', 'callersKnown': fresh and not incomplete}]
            yield entry
